-- ------------------------------------------------------------
-- 9. LOCATIONS   (stable coordinate master for map display)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS locations (
  id            SERIAL PRIMARY KEY,
  name          TEXT NOT NULL UNIQUE,
  latitude      REAL,
  longitude     REAL,
  region        TEXT,
  asset_type    TEXT,
  created_at    TIMESTAMPTZ DEFAULT now()
);

-- link reports to locations (via location_id FK)
ALTER TABLE reports ADD COLUMN IF NOT EXISTS location_id INT REFERENCES locations(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_reports_location_id ON reports(location_id);

-- ------------------------------------------------------------
-- 10. SIF ASSESSMENTS   (from attention model downstream output)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sif_assessments (
  id                SERIAL PRIMARY KEY,
  report_id         INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  attention_level   TEXT,           -- IMMEDIATE | SHORT_TERM | PLANNED | MONITOR
  urgency_score     REAL,
  risk_potential    REAL,
  systemic_attention TEXT,          -- NONE | LOW | MODERATE | HIGH
  systemic_score    REAL,
  confidence        REAL,
  prediction_mode   TEXT,           -- RULE_BASED_COLD_START | HYBRID_ML
  actions           JSONB,         -- list of action recommendations
  drivers           JSONB,         -- list of driver items
  uncertainty       JSONB,         -- missing info, contradictions, etc.
  barrier_failure_rate REAL,
  model_version     TEXT,
  created_at        TIMESTAMPTZ DEFAULT now(),
  UNIQUE(report_id)
);

-- ------------------------------------------------------------
-- 11. BARRIERS / FAILURE AREAS   (IOGP Life-Saving Rules mapped as barriers)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS barriers (
  id       SERIAL PRIMARY KEY,
  code     TEXT NOT NULL UNIQUE,
  name     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS report_barriers (
  report_id     INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  barrier_id    INT NOT NULL REFERENCES barriers(id) ON DELETE CASCADE,
  status        TEXT NOT NULL,   -- BROKEN | NOT_BROKEN | UNCERTAIN | NOT_APPLICABLE
  confidence    REAL,
  reason        TEXT,
  PRIMARY KEY (report_id, barrier_id)
);

-- helpful indices for new tables
CREATE INDEX IF NOT EXISTS idx_sif_assessments_report ON sif_assessments(report_id);
CREATE INDEX IF NOT EXISTS idx_report_barriers_report ON report_barriers(report_id);
CREATE INDEX IF NOT EXISTS idx_locations_name ON locations(name);

