-- ------------------------------------------------------------
-- 1. CORE REPORT STORE   (raw immutable; analysis regenerable)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
  id                      SERIAL PRIMARY KEY,
  incident_id             TEXT NOT NULL UNIQUE,
  location                TEXT,
  event_date              DATE,
  injury_severity         TEXT,
  raw_text                TEXT NOT NULL,
  summary                 TEXT,
  sif_score               REAL NULL,       -- 0..1, from friend's JSON (may be NULL)
  sif_class               TEXT NULL,       -- LOW | MEDIUM | HIGH
  sif_method              TEXT NULL,       -- scoring method
  sif_weight_source       TEXT NULL,       -- weight source
  sif_components          JSONB,           -- score components breakdown
  analysis_json           JSONB,           -- full NLP analysis JSON (source of truth for derived rows)
  edited_at               TIMESTAMPTZ,     -- when an admin last overrode summary/analysis
  created_at              TIMESTAMPTZ DEFAULT now()
);

-- report-level embedding built from a composed "safety representation"
-- Only if pgvector is available
DO $$ BEGIN
  ALTER TABLE reports ADD COLUMN IF NOT EXISTS embedding VECTOR(384);
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

-- ------------------------------------------------------------
-- 2. SAFETY ENTITIES   (two taxonomies: behavioral + hazard/iogp)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS precursors (
  id       SERIAL PRIMARY KEY,
  code     TEXT NOT NULL UNIQUE,          -- safe_work_procedure, energy_isolation, ...
  name     TEXT NOT NULL,
  taxonomy TEXT NOT NULL DEFAULT 'behavioral'  -- 'behavioral' | 'hazard/iogp'
);

CREATE TABLE IF NOT EXISTS report_precursors (
  report_id      INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  precursor_id   INT NOT NULL REFERENCES precursors(id) ON DELETE CASCADE,
  status         TEXT NOT NULL,   -- PRESENT | AMBIGUOUS | NOT_MENTIONED
  confidence     REAL,
  evidence_count INT,
  PRIMARY KEY (report_id, precursor_id)
);

CREATE TABLE IF NOT EXISTS precursor_evidence (
  id            BIGSERIAL PRIMARY KEY,
  report_id     INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  precursor_id  INT NOT NULL REFERENCES precursors(id) ON DELETE CASCADE,
  evidence_text TEXT,
  sentence_id   INT,
  polarity      TEXT,             -- 'present' | 'absent'
  FOREIGN KEY (report_id, precursor_id)
    REFERENCES report_precursors(report_id, precursor_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS hazards (
  id   SERIAL PRIMARY KEY,
  code TEXT UNIQUE,
  name TEXT
);
CREATE TABLE IF NOT EXISTS report_hazards (
  report_id INT REFERENCES reports(id) ON DELETE CASCADE,
  hazard_id INT REFERENCES hazards(id) ON DELETE CASCADE,
  evidence  JSONB,
  PRIMARY KEY (report_id, hazard_id)
);

CREATE TABLE IF NOT EXISTS task_types (
  id   SERIAL PRIMARY KEY,
  code TEXT UNIQUE,
  name TEXT
);
CREATE TABLE IF NOT EXISTS report_task_types (
  report_id    INT REFERENCES reports(id) ON DELETE CASCADE,
  task_type_id INT REFERENCES task_types(id) ON DELETE CASCADE,
  evidence     JSONB,
  PRIMARY KEY (report_id, task_type_id)
);

CREATE TABLE IF NOT EXISTS report_work_changes (
  report_id              INT REFERENCES reports(id) ON DELETE CASCADE PRIMARY KEY,
  work_plan_changed       BOOLEAN,
  unexpected_condition    BOOLEAN,
  task_changed            BOOLEAN,
  equipment_changed       BOOLEAN,
  procedure_changed       BOOLEAN,
  work_sequence_changed   BOOLEAN,
  reassessment_performed  BOOLEAN,
  reassessment_missing    BOOLEAN
);

-- ------------------------------------------------------------
-- 3. FEATURE MIRROR   (mirrors the 70-col encoded CSV)
--    -> powers SQL pattern mining with zero string parsing
--    NOTE: precursor columns are code, name, taxonomy = 3 base;
--          the 13 × 3 (status/confidence/count) and risk flags are
--          generated by the ingest tooling from the CSV header.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_features (
  report_id                 INT REFERENCES reports(id) ON DELETE CASCADE PRIMARY KEY,
  -- risk flags from CSV:
  control_failure_present   BOOLEAN,
  missing_control_present   BOOLEAN,
  barrier_failure_present   BOOLEAN,
  control_deviation_present BOOLEAN,
  -- work-change / info-missing flags and report shape land here at runtime.
  report_length             INTEGER,
  sentence_count            INTEGER,
  relevant_sentence_count   INTEGER,
  relevance_ratio           REAL,
  -- full encoded CSV row (13x3 precursor + extra flags) preserved here:
  features                  JSONB
);

-- ------------------------------------------------------------
-- 4. LIFE-SAVING RULES   (IOGP 9 rules)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS life_saving_rules (
  id          SERIAL PRIMARY KEY,
  rule_id     TEXT NOT NULL UNIQUE,   -- LSR01, LSR02, ...
  name        TEXT NOT NULL,
  description TEXT
);

CREATE TABLE IF NOT EXISTS report_life_saving_rules (
  report_id    INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  lsr_id       INT NOT NULL REFERENCES life_saving_rules(id) ON DELETE CASCADE,
  status       TEXT NOT NULL,          -- BROKEN | NOT_BROKEN | UNCERTAIN | NOT_APPLICABLE
  confidence   REAL,
  reason       TEXT,
  applicable   BOOLEAN,
  PRIMARY KEY (report_id, lsr_id)
);

CREATE TABLE IF NOT EXISTS lsr_evidence (
  id              BIGSERIAL PRIMARY KEY,
  report_id       INT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  lsr_id          INT NOT NULL REFERENCES life_saving_rules(id) ON DELETE CASCADE,
  evidence_text   TEXT,
  sentence_id     INT,
  evidence_type   TEXT,                 -- 'broken' | 'compliance'
  FOREIGN KEY (report_id, lsr_id)
    REFERENCES report_life_saving_rules(report_id, lsr_id) ON DELETE CASCADE
);

-- ------------------------------------------------------------
-- 5. PATTERN INTELLIGENCE
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS patterns (
  id            SERIAL PRIMARY KEY,
  title         TEXT,
  description   TEXT,
  pattern_type  TEXT,             -- 'sql_agg' | 'semantic_cluster' | 'combined'
  confidence    REAL,
  severity      TEXT,
  location      TEXT,
  activity      TEXT,
  precursor_id  INT,
  lsr_id        INT,
  report_count  INT,
  sif_count     INT,
  first_detected DATE,
  last_detected  DATE
);
CREATE TABLE IF NOT EXISTS pattern_reports (
  pattern_id INT REFERENCES patterns(id) ON DELETE CASCADE,
  report_id  INT REFERENCES reports(id) ON DELETE CASCADE,
  similarity REAL,
  PRIMARY KEY (pattern_id, report_id)
);

-- ------------------------------------------------------------
-- 6. RECOMMENDATIONS   (always carry evidence)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recommendations (
  id                SERIAL PRIMARY KEY,
  pattern_id        INT REFERENCES patterns(id) ON DELETE CASCADE,
  barrier_id        INT,
  recommendation    TEXT,
  priority          TEXT,
  intervention_type TEXT,
  confidence        REAL
);
CREATE TABLE IF NOT EXISTS recommendation_evidence (
  id                BIGSERIAL PRIMARY KEY,
  recommendation_id INT REFERENCES recommendations(id) ON DELETE CASCADE,
  evidence_type     TEXT,          -- 'report' | 'kb_document'
  report_id         INT REFERENCES reports(id) ON DELETE CASCADE,
  kb_chunk_id       INT,
  UNIQUE (recommendation_id, evidence_type, report_id, kb_chunk_id)
);

-- ------------------------------------------------------------
-- 7. SAFETY KNOWLEDGE BASE   (RAG citations)
