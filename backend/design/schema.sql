-- ------------------------------------------------------------
-- 14. AUDIT LOG   (append-only, comprehensive)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_log (
  id            BIGSERIAL PRIMARY KEY,
  user_id       INT REFERENCES users(id),
  username      TEXT,
  action        TEXT NOT NULL,        -- summary_edit | analysis_edit | user_role_change | location_change | report_state_change | login
  entity_type   TEXT NOT NULL,        -- report | user | location | pattern | system
  entity_id     TEXT,                 -- incident_id, user_id, etc.
  old_value     JSONB,
  new_value     JSONB,
  ip_address    TEXT,
  created_at    TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_log_entity ON audit_log(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_user ON audit_log(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created ON audit_log(created_at);

-- ------------------------------------------------------------
-- 15. LOCATION RISK SNAPSHOTS   (historical risk tracking)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS location_risk_snapshots (
  id              SERIAL PRIMARY KEY,
  location_id     INT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
  period_start    DATE NOT NULL,
  period_end      DATE NOT NULL,
  risk_score      REAL NOT NULL,
  risk_level      TEXT NOT NULL,
  sif_count       INT DEFAULT 0,
  report_count    INT DEFAULT 0,
  sif_rate        REAL DEFAULT 0,
  trend           TEXT,              -- INCREASING | DECREASING | STABLE | NEWLY_EMERGING
  calculated_at   TIMESTAMPTZ DEFAULT now(),
  UNIQUE(location_id, period_start, period_end)
);
CREATE INDEX IF NOT EXISTS idx_risk_snapshots_location ON location_risk_snapshots(location_id);
CREATE INDEX IF NOT EXISTS idx_risk_snapshots_period ON location_risk_snapshots(period_start, period_end);

